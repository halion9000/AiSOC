"""Generate the AiSOC capability reference from the live routes.

    python -m app.scripts.export_capabilities --full docs/api/AISOC_CAPABILITIES.md --index docs/api/aisoc-areas.md
    python -m app.scripts.export_capabilities --full ... --index ... --check      # exit 1 if either file is out of date

Two outputs from one pass over the application's routes:
  * the FULL reference: every operation, grouped by area, with the permission each one needs and whether it only reads (GET) or changes
  something;
  * the INDEX: one line per area (how many reads and changes, the permissions, a couple of example operations). It is small enough to hand
  to an agent (Cipher's
    knowledge file in the CORE repo is a copy), so the agent can say what AiSOC can do even where it has no tool for it, instead of
    guessing.

What it does NOT say, on purpose: "GET" means the route is declared as a read; it is not proof that the handler never writes. And it grants
nothing: knowing an area exists is not
access to it.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

API_PREFIX = "/api/v1"
READ_METHOD = "GET"
SKIPPED_METHODS = {"HEAD", "OPTIONS"}


@dataclass(frozen=True)
class Op:
    area: str
    method: str
    path: str  # without /api/v1 for routes under it
    outside_api: bool  # True for routes that live outside /api/v1 (single sign-on)
    summary: str
    permissions: tuple[str, ...]
    access: str  # "permission", "signed-in" or "open" (see app.core.route_introspect.access_kind)

    @property
    def is_read(self) -> bool:
        return self.method == READ_METHOD


def _summary(route) -> str:
    text = (route.summary or route.name.replace("_", " ")).strip()
    return (text[:1].upper() + text[1:]) if text else "(no summary)"


def operations(app) -> list[Op]:
    """Every operation of the application, in a stable order (area, path, method)."""
    from app.core.route_introspect import access_kind, required_permissions, walk_routes  # noqa: PLC0415

    out: list[Op] = []
    for full_path, route in walk_routes(app.routes):
        outside = not full_path.startswith(API_PREFIX)
        path = full_path if outside else (full_path[len(API_PREFIX) :] or "/")
        area = path.strip("/").split("/")[0] or "(root)"
        permissions = tuple(sorted(set(required_permissions(route))))
        for method in sorted(route.methods - SKIPPED_METHODS):
            out.append(Op(area, method, path, outside, _summary(route), permissions, access_kind(route)))
    return sorted(out, key=lambda o: (o.area, o.path, o.method))


def _md(text: str) -> str:
    """Make text safe inside a markdown table cell."""
    return re.sub(r"\s+", " ", text).replace("|", "\\|").strip()


SIGNED_IN_TEXT = "signed in, no permission declared (a check may be inside the handler)"
OPEN_TEXT = "no sign-in required (public, or secured another way)"


def _access_text(op: Op) -> str:
    """What protects this operation, said exactly as far as it is known. Never 'login only' for something that may be public or checked
    elsewhere."""
    if op.access == "permission":
        return ", ".join(f"`{p}`" for p in op.permissions)
    return SIGNED_IN_TEXT if op.access == "signed-in" else OPEN_TEXT


def _area_access_text(items: list[Op]) -> str:
    """The permissions an area asks for, then how many of its operations declare none."""
    perms = sorted({p for o in items for p in o.permissions})
    signed_in = sum(o.access == "signed-in" for o in items)
    open_ = sum(o.access == "open" for o in items)
    parts = [", ".join(f"`{p}`" for p in perms)] if perms else []
    if signed_in:
        parts.append(f"{signed_in} signed-in with no permission declared")
    if open_:
        parts.append(f"{open_} with no sign-in required")
    return "; ".join(parts)


def _by_area(ops: list[Op]) -> dict[str, list[Op]]:
    grouped: dict[str, list[Op]] = defaultdict(list)
    for op in ops:
        grouped[op.area].append(op)
    return dict(sorted(grouped.items()))


def render_full(ops: list[Op]) -> str:
    areas = _by_area(ops)
    lines = [
        "# AiSOC capability reference",
        "",
        "<!-- GENERATED by `python -m app.scripts.export_capabilities`: do not edit; a test fails when it is out of date. -->",
        "",
        f"Every operation the API has: **{len(ops)}** operations in **{len(areas)}** areas, generated from the live routes. For each: whether it only reads (`GET`) or changes something, and the permission it needs.",  # noqa: E501
        "",
        "Read this with three cautions. `GET` means the route is *declared* as a read, not proof that the handler never writes. The permission shown is the one the route's dependencies ask for: where none is declared it says so, and a check made inside the handler is not visible here. And knowing an area exists is not access to it: what any caller may do is decided by its permissions or scopes.",  # noqa: E501
        "",
        "## Areas",
        "",
        "| Area | Reads (GET) | Changes | Permissions needed |",
        "| --- | ---: | ---: | --- |",
    ]
    for area, items in areas.items():
        reads = sum(o.is_read for o in items)
        lines.append(
            f"| [{_md(area)}](#{re.sub(r'[^a-z0-9]+', '-', area.lower()).strip('-')}) | {reads} | {len(items) - reads} | {_area_access_text(items)} |"  # noqa: E501
        )
    for area, items in areas.items():
        lines += ["", f"## {_md(area)}", "", "| Method | Path | What it does | Permission |", "| --- | --- | --- | --- |"]
        for o in items:
            where = f"{o.path} (outside `{API_PREFIX}`)" if o.outside_api else o.path
            lines.append(f"| {o.method} | `{_md(where)}` | {_md(o.summary)} | {_access_text(o)} |")
    return "\n".join(lines) + "\n"


def render_index(ops: list[Op], examples: int = 2) -> str:
    areas = _by_area(ops)
    lines = [
        "# AiSOC: what the platform can do, by area",
        "",
        "<!-- GENERATED by `python -m app.scripts.export_capabilities` in the AiSOC repo: do not edit by hand. -->",
        "",
        f"AiSOC has **{len(ops)}** operations in **{len(areas)}** areas. This is a MAP, not a list of tools: Cipher has purpose-built tools for only some of these areas. "  # noqa: E501
        "If a question is about an area with no tool, say what the area is for and that you cannot reach it yet; **never guess its contents, never invent a tool, and never try to call an endpoint directly.** "  # noqa: E501
        "`reads` are operations declared as GET (not proof a handler never writes); `changes` are everything else.",
        "",
    ]
    for area, items in areas.items():
        reads = [o for o in items if o.is_read]
        shown = []
        for o in items:
            text = _md(o.summary)
            if text not in shown:
                shown.append(text)
            if len(shown) == examples:
                break
        lines.append(
            f"- **{_md(area)}**: {len(reads)} reads, {len(items) - len(reads)} changes; protection: {_area_access_text(items)}; e.g. {'; '.join(shown)}"  # noqa: E501
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the AiSOC capability reference from the live routes.")
    parser.add_argument("--full", type=Path, required=True, help="where the full reference goes")
    parser.add_argument("--index", type=Path, required=True, help="where the one-line-per-area index goes")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if either file is not what the routes produce")
    args = parser.parse_args(argv)

    from app.main import app  # noqa: PLC0415

    ops = operations(app)
    outputs = {args.full: render_full(ops), args.index: render_index(ops)}
    if args.check:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("out of date (regenerate with the same command without --check): " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"up to date: {len(ops)} operations")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
